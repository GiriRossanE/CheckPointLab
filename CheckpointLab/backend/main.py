from __future__ import annotations

import json
import os
from copy import deepcopy
from datetime import datetime, timezone
from pathlib import Path
from threading import RLock
from typing import Any
from uuid import uuid4

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

BASE_DIR = Path(__file__).resolve().parent
DATA_DIR = BASE_DIR / "data"
CHECKPOINT_DIR = DATA_DIR / "checkpoints"
STATE_FILE = DATA_DIR / "process_state.json"
DATA_DIR.mkdir(parents=True, exist_ok=True)
CHECKPOINT_DIR.mkdir(parents=True, exist_ok=True)

lock = RLock()
failure_at: int | None = None
app = FastAPI(
    title="CheckpointLab API",
    description="Process checkpoint and rollback recovery simulator for an OS course.",
    version="1.0.0",
)
app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:5173",
        "http://127.0.0.1:5173",
    ],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def initial_state(total_work: int = 100) -> dict[str, Any]:
    return {
        "process_id": "PROC-001",
        "total_work": total_work,
        "progress": 0,
        "state": "Ready",
        "failure_count": 0,
        "recovery_count": 0,
        "created_at": now_iso(),
        "updated_at": now_iso(),
        "events": [
            {
                "id": str(uuid4()),
                "time": now_iso(),
                "type": "system",
                "message": "Process initialized and ready.",
                "progress": 0,
            }
        ],
    }


def write_json(path: Path, value: Any) -> None:
    temp_path = path.with_suffix(path.suffix + ".tmp")
    temp_path.write_text(json.dumps(value, indent=2), encoding="utf-8")
    os.replace(temp_path, path)


def read_json(path: Path, default: Any) -> Any:
    if not path.exists():
        return deepcopy(default)
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return deepcopy(default)


state: dict[str, Any] = read_json(STATE_FILE, initial_state())
if not isinstance(state, dict) or "progress" not in state:
    state = initial_state()
checkpoints: list[dict[str, Any]] = []
for path in sorted(CHECKPOINT_DIR.glob("CP-*.json")):
    item = read_json(path, None)
    if isinstance(item, dict) and "id" in item and "snapshot" in item:
        checkpoints.append(item)


def persist_state() -> None:
    state["updated_at"] = now_iso()
    write_json(STATE_FILE, state)


def add_event(event_type: str, message: str) -> None:
    state["events"].insert(
        0,
        {
            "id": str(uuid4()),
            "time": now_iso(),
            "type": event_type,
            "message": message,
            "progress": state["progress"],
        },
    )
    state["events"] = state["events"][:150]


class RunRequest(BaseModel):
    units: int = Field(default=10, ge=1, le=1000)


class FailureConfigRequest(BaseModel):
    failure_at: int | None = Field(default=None, ge=0, le=100000)


class ResetRequest(BaseModel):
    total_work: int = Field(default=100, ge=1, le=100000)


class CheckpointRequest(BaseModel):
    label: str | None = Field(default=None, max_length=60)


def checkpoint_path(checkpoint_id: str) -> Path:
    # IDs are generated by this server; restrict characters before using a path.
    if not checkpoint_id.startswith("CP-") or not all(
        ch.isalnum() or ch == "-" for ch in checkpoint_id
    ):
        raise HTTPException(status_code=400, detail="Invalid checkpoint ID.")
    return CHECKPOINT_DIR / f"{checkpoint_id}.json"


def public_snapshot() -> dict[str, Any]:
    return {
        "process_id": state["process_id"],
        "total_work": state["total_work"],
        "progress": state["progress"],
        "state": state["state"],
        "failure_count": state["failure_count"],
        "recovery_count": state["recovery_count"],
        "updated_at": state["updated_at"],
    }


def metrics() -> dict[str, Any]:
    latest = checkpoints[-1] if checkpoints else None
    saved_progress = latest["snapshot"]["progress"] if latest else 0
    return {
        "progress_percent": round(state["progress"] / state["total_work"] * 100, 1),
        "checkpoint_count": len(checkpoints),
        "failure_count": state["failure_count"],
        "recovery_count": state["recovery_count"],
        "latest_checkpoint_id": latest["id"] if latest else None,
        "latest_checkpoint_progress": saved_progress if latest else None,
        "work_since_latest_checkpoint": max(0, state["progress"] - saved_progress),
    }


def dashboard() -> dict[str, Any]:
    return {
        "process": public_snapshot(),
        "metrics": metrics(),
        "checkpoints": [
            {
                "id": cp["id"],
                "label": cp.get("label") or cp["id"],
                "progress": cp["snapshot"]["progress"],
                "total_work": cp["snapshot"]["total_work"],
                "created_at": cp["created_at"],
                "state": cp["snapshot"]["state"],
            }
            for cp in reversed(checkpoints)
        ],
        "events": state["events"],
    }


@app.get("/")
def root() -> dict[str, str]:
    return {"name": "CheckpointLab API", "status": "running", "docs": "/docs"}


@app.get("/api/dashboard")
def get_dashboard() -> dict[str, Any]:
    with lock:
        return dashboard()


@app.post("/api/process/run")

@app.post("/api/process/run")
def run_process(request: RunRequest) -> dict[str, Any]:
    global failure_at

    with lock:
        if state["state"] == "Failed":
            raise HTTPException(
                status_code=409,
                detail="Recover from a checkpoint before running again.",
            )

        if state["state"] in ("Paused", "Completed"):
            raise HTTPException(
                status_code=409,
                detail=f"Cannot run while process state is {state['state']}.",
            )

        start = state["progress"]
        target = min(
            state["total_work"],
            start + request.units,
        )

        # Inject a failure if execution reaches the configured point.
        if failure_at is not None and start < failure_at <= target:
            state["progress"] = failure_at
            state["state"] = "Failed"
            state["failure_count"] += 1

            add_event(
                "failure",
                f"Injected failure at work unit {failure_at}.",
            )

            failure_at = None
            persist_state()
            return dashboard()

        state["state"] = "Running"
        state["progress"] = target

        if target >= state["total_work"]:
            state["state"] = "Completed"
            add_event(
                "success",
                f"Process completed at {target} / {state['total_work']} units.",
            )
        else:
            state["state"] = "Ready"
            add_event(
                "execution",
                f"Executed {target - start} work units.",
            )

        persist_state()
        return dashboard()

@app.post("/api/process/pause")
def pause_process() -> dict[str, Any]:
    with lock:
        if state["state"] != "Ready":
            raise HTTPException(
                status_code=409,
                detail="Only a ready process can be paused.",
            )

        state["state"] = "Paused"
        add_event("system", "Process paused by the user.")
        persist_state()
        return dashboard()


@app.post("/api/process/resume")
def resume_process() -> dict[str, Any]:
    with lock:
        if state["state"] != "Paused":
            raise HTTPException(
                status_code=409,
                detail="Only a paused process can be resumed.",
            )

        state["state"] = "Ready"
        add_event("system", "Process resumed by the user.")
        persist_state()
        return dashboard()


@app.post("/api/process/failure-config")
def configure_failure(
    request: FailureConfigRequest,
) -> dict[str, Any]:
    global failure_at

    with lock:
        if state["state"] in ("Failed", "Completed"):
            raise HTTPException(
                status_code=409,
                detail="Reset or recover the process before configuring failure.",
            )

        if request.failure_at is not None:
            if request.failure_at <= state["progress"]:
                raise HTTPException(
                    status_code=400,
                    detail="Failure point must be greater than current progress.",
                )

            if request.failure_at > state["total_work"]:
                raise HTTPException(
                    status_code=400,
                    detail="Failure point cannot exceed total work.",
                )

        failure_at = request.failure_at

        if failure_at is None:
            message = "Scheduled failure injection disabled."
        else:
            message = f"Failure scheduled at work unit {failure_at}."

        add_event("system", message)
        persist_state()
        return dashboard()

@app.post("/api/checkpoints")
def create_checkpoint(request: CheckpointRequest) -> dict[str, Any]:
    with lock:
        if state["state"] == "Failed":
            raise HTTPException(status_code=409, detail="Cannot checkpoint a failed process. Recover first.")
        sequence = len(checkpoints) + 1
        checkpoint_id = f"CP-{sequence:03d}"
        while checkpoint_path(checkpoint_id).exists():
            sequence += 1
            checkpoint_id = f"CP-{sequence:03d}"

        snapshot = {
            "process_id": state["process_id"],
            "total_work": state["total_work"],
            "progress": state["progress"],
            "state": state["state"],
            "failure_count": state["failure_count"],
            "recovery_count": state["recovery_count"],
            "events": deepcopy(state["events"]),
        }
        checkpoint = {
            "id": checkpoint_id,
            "label": (request.label or "").strip() or checkpoint_id,
            "created_at": now_iso(),
            "snapshot": snapshot,
        }
        write_json(checkpoint_path(checkpoint_id), checkpoint)
        checkpoints.append(checkpoint)
        add_event("checkpoint", f"Saved {checkpoint_id} at work unit {state['progress']}.")
        persist_state()
        return dashboard()


@app.post("/api/process/crash")
def simulate_crash() -> dict[str, Any]:
    with lock:
        if state["state"] == "Failed":
            raise HTTPException(status_code=409, detail="The process is already failed. Recover it first.")
        if state["state"] == "Completed":
            raise HTTPException(status_code=409, detail="A completed process cannot be crashed. Reset first.")
        state["state"] = "Failed"
        state["failure_count"] += 1
        add_event("failure", f"Simulated process failure at work unit {state['progress']}.")
        persist_state()
        return dashboard()


@app.post("/api/process/recover")
def recover_process(checkpoint_id: str | None = None) -> dict[str, Any]:
    with lock:
        if not checkpoints:
            raise HTTPException(status_code=404, detail="No checkpoints exist yet. Save a checkpoint first.")
        selected = None
        if checkpoint_id:
            selected = next((cp for cp in checkpoints if cp["id"] == checkpoint_id), None)
            if selected is None:
                raise HTTPException(status_code=404, detail=f"Checkpoint {checkpoint_id} was not found.")
        else:
            selected = checkpoints[-1]

        failed_progress = state["progress"]
        snapshot = deepcopy(selected["snapshot"])
        lost_work = max(0, failed_progress - snapshot["progress"])

        state.update(snapshot)
        state["state"] = "Ready" if state["progress"] < state["total_work"] else "Completed"
        state["recovery_count"] += 1
        add_event(
            "recovery",
            f"Recovered from {selected['id']} at unit {state['progress']}. "
            f"{lost_work} unit(s) of work were rolled back.",
        )
        persist_state()
        result = dashboard()
        result["last_recovery"] = {
            "checkpoint_id": selected["id"],
            "restored_progress": state["progress"],
            "lost_work": lost_work,
            "recovery_count": state["recovery_count"],
        }
        return result


@app.post("/api/process/reset")
def reset_process(request: ResetRequest) -> dict[str, Any]:
    global state
    with lock:
        state = initial_state(request.total_work)
        state["process_id"] = f"PROC-{datetime.now().strftime('%H%M%S')}"
        add_event("system", f"New process initialized with {request.total_work} work units.")
        persist_state()
        return dashboard()


@app.delete("/api/checkpoints/{checkpoint_id}")
def delete_checkpoint(checkpoint_id: str) -> dict[str, Any]:
    with lock:
        path = checkpoint_path(checkpoint_id)
        selected = next((cp for cp in checkpoints if cp["id"] == checkpoint_id), None)
        if selected is None or not path.exists():
            raise HTTPException(status_code=404, detail="Checkpoint not found.")
        path.unlink()
        checkpoints.remove(selected)
        # Renumbering is intentionally avoided so IDs remain stable in event logs.
        add_event("system", f"Deleted checkpoint {checkpoint_id}.")
        persist_state()
        return dashboard()
